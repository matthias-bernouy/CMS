const RESERVED_SETTING_ATTRIBUTE_PREFIXES = ["aria-", "cms-", "data-", "on"] as const;

export function blocSettingAttributeNameIssue(name: string, acceptedTags: readonly string[]): string | null {
    const attribute = name.toLowerCase();
    if (
        GLOBAL_RESERVED_SETTING_ATTRIBUTES.has(attribute) ||
        RESERVED_SETTING_ATTRIBUTE_PREFIXES.some((prefix) => attribute.startsWith(prefix))
    ) {
        return `setting attribute ${JSON.stringify(name)} is reserved by the platform`;
    }
    for (const tag of acceptedTags) {
        const normalizedTag = tag.toLowerCase();
        if (
            PLATFORM_NATIVE_ATTRIBUTES[normalizedTag]?.has(attribute) ||
            RESERVED_SETTING_ATTRIBUTES_BY_TAG[normalizedTag]?.has(attribute)
        ) {
            return `setting attribute ${JSON.stringify(name)} is reserved by native <${normalizedTag}>`;
        }
    }
    return null;
}

const NATIVE_BOOLEAN_ATTRIBUTES = new Set([
    "checked",
    "default",
    "disabled",
    "hidden",
    "inert",
    "multiple",
    "readonly",
    "required",
    "selected",
]);

type NativeAttributeBindingKind = "boolean" | "string";

export function nativeAttributeBindingKind(attribute: string): NativeAttributeBindingKind {
    return NATIVE_BOOLEAN_ATTRIBUTES.has(attribute.toLowerCase()) ? "boolean" : "string";
}

export function isDeclaredPlatformNativeAttributeAllowed(tag: string, attribute: string): boolean {
    return PLATFORM_NATIVE_ATTRIBUTES[tag.toLowerCase()]?.has(attribute.toLowerCase()) === true;
}
